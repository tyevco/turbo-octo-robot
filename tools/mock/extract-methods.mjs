#!/usr/bin/env node
// Extracts the element method allowlist the gpui mock validates against.
//
// Input:  docs/research/gpui-kit.d.ts (the reconstructed declarations herdr
//         0.1.18 / gpui-shell 0.7.1 writes; see docs/research/gpui-ui.md §1).
// Output: tools/mock/gpui-methods.json  (canonical, ARCHITECTURE A8)
//         tools/mock/gpui-methods.js    (the same data as an ES module, because
//                                        the QuickJS harness loads plain ES
//                                        modules and has no JSON import)
//
// The `NativeElement` interface is laid out by typings.rs in a fixed order:
// hand-written element methods (ELEMENT_METHODS), the three inline-token
// methods, then the generated style surface — parametric styles
// (`name(this: Self, value: <Kind>)`) followed by nullary styles
// (`name(this: Self)`). Everything before the style surface is a behaviour.
//
// Usage: node tools/mock/extract-methods.mjs [--check]
//   --check  exit 1 when the committed outputs differ from a fresh extraction.

import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const SOURCE = "docs/research/gpui-kit.d.ts";

const PARAM_KINDS = new Set(["Color", "Length", "DefiniteLength", "AbsoluteLength", "number", "string"]);

/** Lines of `interface <name> ... {` up to its closing `  }` at the same indent. */
function interfaceBody(lines, name) {
  const start = lines.findIndex((line) => new RegExp(`^  export interface ${name}\\b.*\\{\\s*$`).test(line));
  if (start < 0) throw new Error(`interface ${name} not found in ${SOURCE}`);
  const end = lines.findIndex((line, index) => index > start && line === "  }");
  if (end < 0) throw new Error(`interface ${name} has no closing brace`);
  return { start, body: lines.slice(start + 1, end) };
}

/** Method declarations at member indent (4 spaces), with the text up to `): ...;`. */
function methods(body) {
  const out = [];
  for (let index = 0; index < body.length; index++) {
    const match = /^    ([A-Za-z_][A-Za-z0-9_]*)\s*[<(]/.exec(body[index]);
    if (!match) continue;
    let text = body[index];
    while (!/\)\s*:\s*[^;]*;\s*$/.test(text) && index + 1 < body.length) {
      index += 1;
      text += " " + body[index].trim();
    }
    out.push({ name: match[1], text });
  }
  return out;
}

export function extract(dts) {
  const lines = dts.split("\n");
  const version = /for gpui-shell ([0-9.]+)/.exec(dts)?.[1] ?? null;

  const native = methods(interfaceBody(lines, "NativeElement").body);
  const styleStart = native.findIndex((m) => m.name === "on_token_hover") + 1;
  if (styleStart <= 0) throw new Error("style section anchor `on_token_hover` not found");

  const behaviors = [];
  const nullary = [];
  const param = {};
  for (const [index, method] of native.entries()) {
    if (index < styleStart) {
      behaviors.push(method.name);
      continue;
    }
    const paramMatch = /\(this: Self, value: ([A-Za-z]+)\): Self;$/.exec(method.text);
    if (paramMatch) {
      if (!PARAM_KINDS.has(paramMatch[1])) throw new Error(`unexpected argument kind ${paramMatch[1]} on ${method.name}`);
      param[method.name] = paramMatch[1];
    } else if (/\(this: Self\): Self;$/.test(method.text)) {
      nullary.push(method.name);
    } else {
      throw new Error(`unrecognised style declaration: ${method.text}`);
    }
  }

  const textView = methods(interfaceBody(lines, "TextViewElement").body).map((m) => m.name);

  const anchorAt = lines.findIndex((line) => /^  export type Anchor =\s*$/.test(line));
  if (anchorAt < 0) throw new Error("type Anchor not found");
  const anchors = [];
  for (let index = anchorAt + 1; /^\s*\|/.test(lines[index]); index++) {
    anchors.push(/"([^"]+)"/.exec(lines[index])[1]);
  }

  const unique = (list) => [...new Set(list)].sort();
  return {
    source: SOURCE,
    sha256: createHash("sha256").update(dts).digest("hex"),
    shell: version,
    counts: {
      behaviors: unique(behaviors).length,
      nullary: unique(nullary).length,
      param: Object.keys(param).length,
    },
    behaviors: unique(behaviors),
    param: Object.fromEntries(Object.keys(param).sort().map((name) => [name, param[name]])),
    nullary: unique(nullary),
    components: { TextView: unique(textView) },
    anchors,
  };
}

export function render(data) {
  const json = JSON.stringify(data, null, 1) + "\n";
  const js =
    "// Generated by tools/mock/extract-methods.mjs from " + SOURCE + ". Do not edit.\n" +
    "// Same data as gpui-methods.json, as an ES module for the QuickJS harness.\n" +
    "export default " + JSON.stringify(data) + ";\n";
  return { json, js };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const dts = readFileSync(join(root, SOURCE), "utf8");
  const { json, js } = render(extract(dts));
  const jsonPath = join(here, "gpui-methods.json");
  const jsPath = join(here, "gpui-methods.js");
  if (process.argv.includes("--check")) {
    const same = (path, text) => {
      try { return readFileSync(path, "utf8") === text; } catch { return false; }
    };
    if (!same(jsonPath, json) || !same(jsPath, js)) {
      console.error("gpui-methods.json / gpui-methods.js are stale; run node tools/mock/extract-methods.mjs");
      process.exit(1);
    }
    console.log("gpui-methods up to date");
  } else {
    writeFileSync(jsonPath, json);
    writeFileSync(jsPath, js);
    const data = JSON.parse(json);
    console.log(`wrote ${jsonPath}: ${data.counts.behaviors} behaviours, ${data.counts.param} parametric, ${data.counts.nullary} nullary`);
  }
}
